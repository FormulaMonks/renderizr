#! /usr/bin/env node
/**
 * Writes `scripts/mermaid/parser.js`, the Mermaid reader the build runs
 * (ADR 24): Mermaid's own flowchart, ERD and sequence grammars and db
 * classes, its frontmatter and directive reader and its theme code, at the
 * tag `MERMAID_VERSION` pins, cut loose from Mermaid core by `plugins.js`.
 * `pnpm mermaid:parser` runs it.
 *
 * It checks Mermaid's source out at the tag and installs the bundling tools
 * into a work folder of its own, so neither `mermaid` nor Jison ever enters
 * Renderizr's dependencies. Every path the bundle names is relative to that
 * folder, so two runs write the same bytes on any machine.
 *
 * Renovate raises `MERMAID_VERSION` (the custom manager in `renovate.json`);
 * its pull request then needs this script's output committed.
 */

import { execFileSync } from "node:child_process";
import {
    copyFileSync,
    existsSync,
    mkdirSync,
    readFileSync,
    writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { trim } from "./plugins.js";

/** The Mermaid release the parser is generated from. */
// renovate: datasource=npm depName=mermaid
export const MERMAID_VERSION = "12.2.0";

/**
 * The tools the bundle is made with, pinned so a rerun at the same Mermaid
 * version writes the same bytes. `mermaid` itself is only there for its
 * published default config, and `khroma` is Mermaid's own dependency,
 * pinned here because the parser bundles it.
 */
const TOOLS = {
    esbuild: "0.28.2",
    jison: "0.4.18",
    "js-yaml": "5.4.3",
    khroma: "2.1.0",
    mermaid: MERMAID_VERSION,
};

const here = import.meta.dirname;
const OUTFILE = resolve(here, "../parser.js");

const run = (command, args, cwd) =>
    execFileSync(command, args, {
        cwd,
        stdio: ["ignore", "ignore", "inherit"],
    });

/** The work folder: Mermaid's source at the tag, the tools, the entry and the stub. */
function prepare(work) {
    const checkout = join(work, "mermaid");
    if (!existsSync(checkout)) {
        process.stdout.write(`Checking out mermaid@${MERMAID_VERSION}\n`);
        run("git", [
            "-c",
            "advice.detachedHead=false",
            "clone",
            "--quiet",
            "--depth",
            "1",
            "--branch",
            `mermaid@${MERMAID_VERSION}`,
            "--filter=blob:none",
            "--sparse",
            "https://github.com/mermaid-js/mermaid.git",
            checkout,
        ]);
        run(
            "git",
            ["sparse-checkout", "set", "packages/mermaid/src"],
            checkout,
        );
    }
    if (!existsSync(join(work, "node_modules", "esbuild"))) {
        process.stdout.write("Installing the bundling tools\n");
        writeFileSync(
            join(work, "package.json"),
            `${JSON.stringify({ private: true, type: "module" })}\n`,
        );
        run(
            "npm",
            [
                "install",
                "--no-audit",
                "--no-fund",
                "--no-save",
                ...Object.entries(TOOLS).map(([name, v]) => `${name}@${v}`),
            ],
            work,
        );
    }
    mkdirSync(join(work, "src"), { recursive: true });
    copyFileSync(join(here, "entry.js"), join(work, "src", "entry.js"));
    copyFileSync(join(here, "stub.js"), join(work, "src", "stub.js"));
}

/** Mermaid's MIT notice, from its checkout, as the comment the parser opens with. */
function notice(work) {
    const license = readFileSync(join(work, "mermaid", "LICENSE"), "utf8")
        .trim()
        .split("\n")
        .map((line) => ` *${line ? ` ${line}` : ""}`)
        .join("\n");
    return `/*
 * Generated by \`pnpm mermaid:parser\` (scripts/mermaid/generate) from
 * mermaid@${MERMAID_VERSION}. Do not edit: change the generator and run it again.
 * It bundles js-yaml and khroma too; THIRD-PARTY-NOTICES.md lists all three.
 *
${license}
 */
`;
}

/**
 * Where the checkout and the bundling tools are kept between runs: the
 * user's own cache folder, not a shared temp folder another user could fill
 * first, and outside the repo, whose `tsconfig.json` would change the bundle.
 */
const CACHE = join(
    process.env.XDG_CACHE_HOME || join(homedir(), ".cache"),
    `renderizr-mermaid-${MERMAID_VERSION}`,
);

export async function generate(work = CACHE) {
    mkdirSync(work, { recursive: true });
    prepare(work);
    const require = createRequire(join(work, "package.json"));
    const esbuild = require("esbuild");
    const jison = require("jison");
    const { default: mermaid } = await import(
        pathToFileURL(require.resolve("mermaid"))
    );
    const stub = join(work, "src", "stub.js");
    const result = await esbuild.build({
        absWorkingDir: work,
        entryPoints: ["src/entry.js"],
        bundle: true,
        format: "esm",
        platform: "node",
        target: "node20",
        write: false,
        inject: [stub],
        plugins: [
            trim({
                stub,
                jison,
                defaultConfig: mermaid.mermaidAPI.defaultConfig,
            }),
        ],
        logLevel: "error",
    });
    writeFileSync(OUTFILE, notice(work) + result.outputFiles[0].text);
    process.stdout.write(`Wrote ${OUTFILE}\n`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
    await generate(process.argv[2] && resolve(process.argv[2]));
}
