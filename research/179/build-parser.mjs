// Generates scripts/mermaid/parser.js: Mermaid's own flowchart, ERD and sequence grammars and db classes, trimmed the
// way research 177 measured them. Needs the research 177 harness set up (branch chore/177/research-mermaid-parsing,
// research/177/setup.sh); pass its folder as the first argument.
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createRequire } from "node:module";

const harness = resolve(process.argv[2] ?? "");
const require = createRequire(join(harness, "package.json"));
const esbuild = require("esbuild");
const { default: trim } = await import(
    join(harness, "scripts/trim-plugin.mjs")
);

const outfile = resolve(import.meta.dirname, "../../scripts/mermaid/parser.js");
const result = await esbuild.build({
    entryPoints: [join(harness, "scripts/entries/trimmed-read.mjs")],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node20",
    write: false,
    plugins: [trim],
    logLevel: "error",
});
writeFileSync(
    outfile,
    `// Generated by research/179/build-parser.mjs from mermaid@12.2.0 (MIT, Copyright (c) 2014 - 2022 Knut Sveidqvist). Do not edit.\n${result.outputFiles[0].text}`,
);
console.log(`wrote ${outfile}`);
